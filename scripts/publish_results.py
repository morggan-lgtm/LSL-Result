#!/usr/bin/env python3
"""Publish completed LSL TUI sessions to the LSL-Result GitHub Pages repo.

Run once:
  python3 scripts/publish_results.py --source-root /path/to/AI-Agent --push

Keep watching for new completed sessions:
  python3 scripts/publish_results.py --source-root /path/to/AI-Agent --watch --push

Git authentication must already be configured on this computer. No token is
stored by this script. Without --push, it only prepares files in this repo.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path


CARD_RE = re.compile(r"LSL-\d{4}$")
AXES = ("volatility", "chemistry", "intensity", "valence", "persistence")
RECOMMENDED = {
    "gj887b": "Rotten egg",
    "hd20794d": "Ozonic accord",
    "kepler22b": "Rain / Ocean",
    "kepler442b": "Wet soil",
    "taucetf": "Old paper",
}
REPO_ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as stream:
        return json.load(stream)


def write_if_changed(path: Path, contents: bytes) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_bytes() == contents:
        return False
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(contents)
    temporary.replace(path)
    return True


def copy_if_changed(source: Path, target: Path) -> bool:
    if target.is_file() and sha256(source) == sha256(target):
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.name + ".tmp")
    shutil.copyfile(source, temporary)
    temporary.replace(target)
    return True


def inside(path: Path, root: Path) -> Path:
    resolved = path.resolve()
    if not resolved.is_relative_to(root.resolve()):
        raise ValueError(f"Source path is outside AI-Agent: {resolved}")
    return resolved


def run_git(*args: str, repo: Path) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env["GIT_TERMINAL_PROMPT"] = "0"
    return subprocess.run(["git", *args], cwd=repo, env=env, text=True,
                          check=True, capture_output=True)


def verify_repo(repo: Path) -> None:
    remote = run_git("remote", "get-url", "origin", repo=repo).stdout.strip()
    if not remote.rstrip("/").endswith("morggan-lgtm/LSL-Result.git"):
        raise ValueError(f"Unexpected Git origin: {remote}")
    branch = run_git("branch", "--show-current", repo=repo).stdout.strip()
    if branch != "main":
        raise ValueError(f"Expected main branch, found {branch!r}")


def publish_git(repo: Path) -> bool:
    verify_repo(repo)
    if run_git("status", "--porcelain", repo=repo).stdout.strip():
        # The only expected changes are the files generated by this script.
        changed = run_git("status", "--porcelain", repo=repo).stdout.splitlines()
        allowed = ("results/", "posters/", "pom/", "drawings/")
        unrelated = [line for line in changed if not line[3:].startswith(allowed)]
        if unrelated:
            raise RuntimeError("Other local changes are present: " + ", ".join(unrelated))
    run_git("add", "--", "results", "posters", "pom", "drawings", repo=repo)
    staged = run_git("diff", "--cached", "--name-only", repo=repo).stdout.strip()
    if staged:
        run_git("commit", "-m", "Publish completed LSL participant results", repo=repo)
    ahead = int(run_git("rev-list", "--count", "origin/main..HEAD", repo=repo).stdout.strip())
    if not ahead:
        return False
    run_git("push", "origin", "main", repo=repo)
    return True


def make_poster(source: Path, target: Path, source_hash: str, previous_hash: str | None) -> bool:
    if target.is_file() and source_hash == previous_hash:
        return False
    if not shutil.which("sips"):
        raise RuntimeError("macOS sips is required to create the JPEG poster")
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.stem + ".tmp.jpg")
    subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "82",
                    "-Z", "1200", str(source), "--out", str(temporary)],
                   check=True, stdout=subprocess.DEVNULL)
    temporary.replace(target)
    return True


def make_result(session: dict, source_root: Path, repo: Path) -> bool:
    card = session.get("card_id") or session.get("sample_id", "")
    if not CARD_RE.fullmatch(card) or session.get("stage") != "completed":
        return False
    planet_id = session.get("assigned_planet")
    m5 = (session.get("m5") or {}).get("result") or {}
    if not planet_id or m5.get("participant_id") != card or m5.get("planet_id") != planet_id:
        print(f"Skip {card}: incomplete or mismatched M5 result", file=sys.stderr)
        return False

    raw = session.get("raw") or {}
    if not all(raw.get(key) for key in ("PART_1", "PART_2", "PART_3")):
        print(f"Skip {card}: incomplete TUI stations", file=sys.stderr)
        return False

    tui_root = source_root / "LSL-M1" / "tui_runtime"
    image = inside(Path(m5["image_path"]), source_root)
    pom = inside(Path(session["pom_path"]), source_root)
    drawing = inside(source_root / "TUI_Processing_v5" / "collected_data" /
                     raw["PART_3"]["pixel_art_path"], source_root)
    planet_root = source_root / "LSL-M0" / "planets"
    planet_file = planet_root / planet_id / "params.json"
    required = (image, pom, drawing, planet_file)
    if not all(path.is_file() for path in required):
        print(f"Skip {card}: waiting for {', '.join(str(p) for p in required if not p.is_file())}", file=sys.stderr)
        return False

    planet = read_json(planet_file)
    hard = planet["hard_data"]
    result_path = repo / "results" / f"{card}.json"
    old = read_json(result_path) if result_path.is_file() else {}
    image_hash = sha256(image)
    poster_path = repo / "posters" / f"{card}.jpg"
    changed = make_poster(image, poster_path, image_hash,
                          (old.get("source") or {}).get("image_sha256"))
    changed |= copy_if_changed(pom, repo / "pom" / f"{card}.png")
    changed |= copy_if_changed(drawing, repo / "drawings" / f"{card}.png")

    scores = []
    for score_planet, probability in (session.get("probabilities") or {}).items():
        other = read_json(planet_root / score_planet / "params.json")
        scores.append({"planet_id": score_planet, "display_name": other["display_name"],
                       "p": round(float(probability), 4)})
    if not scores or abs(sum(item["p"] for item in scores) - 1) > 0.001:
        raise ValueError(f"Invalid planet probabilities for {card}")

    document = {
        "card_id": card,
        "created_at": datetime.fromtimestamp(image.stat().st_mtime, timezone.utc)
                              .isoformat(timespec="milliseconds").replace("+00:00", "Z"),
        "planet": {
            "id": planet_id, "display_name": planet["display_name"],
            "star_class": hard["star_class"], "teq_k": hard["teq_k"]["value"],
            "mass_earth": hard["mass_earth"]["value"],
            "tidally_locked": hard.get("tidally_locked"),
            "descriptors": planet.get("descriptors", []),
            "earth_memory": planet["earth_memory"]["one_line"],
            "earth_memory_zh_tw": planet["earth_memory"].get("one_line_zh_tw", ""),
            "sensory_anchors": planet["earth_memory"].get("sensory_anchors", []),
            "recommended_scent": RECOMMENDED.get(planet_id, ""),
            "display_color": planet.get("comfy_prompt", {}).get("display_color")
                             or planet.get("display_color", "#a0522d"),
        },
        "odour_vector": {key: round(float(value), 4) for key, value in
                         zip(AXES, session["odour_vector"])},
        "planet_vector": {key: planet["odour_axes"][key] for key in AXES},
        "scores": scores,
        "dialogue": m5.get("dialogue") or "",
        "poster": f"posters/{card}.jpg",
        "tui": {
            "part1": raw["PART_1"],
            "part2": raw["PART_2"],
            "part3": {key: value for key, value in raw["PART_3"].items()
                      if key not in ("pixel_art_path", "trace_path")},
        },
        "assets": {"pom": f"pom/{card}.png", "drawing": f"drawings/{card}.png"},
        "source": {"revision": session.get("revision"),
                   "generation_key": (session.get("generation") or {}).get("key"),
                   "image_sha256": image_hash},
    }
    changed |= write_if_changed(result_path,
                                (json.dumps(document, ensure_ascii=False, indent=2) + "\n").encode())
    if changed:
        print(f"Prepared {card}: {planet['display_name']}")
    return changed


def run_once(source_root: Path, repo: Path, push: bool) -> int:
    if push:
        verify_repo(repo)
        if run_git("status", "--porcelain", repo=repo).stdout.strip():
            raise RuntimeError("Git checkout has local changes; publish or discard them first")
        run_git("pull", "--ff-only", "origin", "main", repo=repo)
    pipeline_path = source_root / "LSL-M1" / "tui_runtime" / "pipeline.json"
    pipeline = read_json(pipeline_path)
    changed = 0
    for session in pipeline.get("sessions", []):
        changed += make_result(session, source_root, repo)
    if push:
        published = publish_git(repo)
        print("Pushed results to GitHub" if published else "GitHub already up to date")
    elif changed:
        print("Files prepared locally; use --push to publish")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", required=True, type=Path,
                        help="Local AI-Agent project directory")
    parser.add_argument("--repo", type=Path, default=REPO_ROOT,
                        help="Local LSL-Result Git checkout (default: this script's repo)")
    parser.add_argument("--push", action="store_true", help="Commit and push to GitHub")
    parser.add_argument("--watch", action="store_true", help="Keep checking for completed sessions")
    parser.add_argument("--interval", type=int, default=10, help="Watch interval in seconds")
    args = parser.parse_args()
    source_root = args.source_root.expanduser().resolve()
    repo = args.repo.expanduser().resolve()
    if not source_root.is_dir() or not repo.is_dir():
        parser.error("--source-root and --repo must be existing directories")
    if args.interval < 2:
        parser.error("--interval must be at least 2 seconds")
    while True:
        try:
            run_once(source_root, repo, args.push)
        except (OSError, ValueError, KeyError, RuntimeError, subprocess.CalledProcessError) as error:
            print(f"Publish failed: {error}", file=sys.stderr)
            if not args.watch:
                return 1
        if not args.watch:
            return 0
        time.sleep(args.interval)


if __name__ == "__main__":
    raise SystemExit(main())
